import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { QueryRunner } from 'typeorm';

interface Baseline {
  columnas: Array<{
    tabla: string;
    columna: string;
    tipo: string;
    obligatoria: boolean;
    identidad: string;
    valor_por_defecto: string | null;
  }>;
  restricciones: Array<{
    tabla: string;
    nombre: string;
    tipo: string;
    definicion: string;
  }>;
  indices: Array<{ tabla: string; nombre: string; definicion: string }>;
  seguridad: Array<{ tabla: string; rls: boolean; forzar_rls: boolean }>;
}

/** Recrea la referencia estructural en un esquema aislado dentro de una transacción activa. */
export async function createBaseline(
  runner: QueryRunner,
  schemaName: string,
): Promise<void> {
  const quote = (name: string) => runner.connection.driver.escape(name);
  const schema = quote(schemaName);
  await runner.query(`CREATE SCHEMA ${schema}`);
  await runner.query(`SET LOCAL search_path TO ${schema}, pg_catalog`);
  const baseline = JSON.parse(
    readFileSync(
      resolve(__dirname, '../../src/db/baseline/esquema-inicial.json'),
      'utf8',
    ),
  ) as Baseline;
  for (const table of baseline.seguridad) {
    const definitions = baseline.columnas
      .filter((column) => column.tabla === table.tabla)
      .map((column) => {
        const identity =
          column.identidad === 'd' ? ' GENERATED BY DEFAULT AS IDENTITY' : '';
        const required = column.obligatoria ? ' NOT NULL' : '';
        const defaultValue = column.valor_por_defecto
          ? ` DEFAULT ${column.valor_por_defecto}`
          : '';
        return `${quote(column.columna)} ${column.tipo}${identity}${required}${defaultValue}`;
      });
    await runner.query(
      `CREATE TABLE ${schema}.${quote(table.tabla)} (${definitions.join(', ')})`,
    );
  }
  // Las claves referenciadas deben existir antes de incorporar las claves foráneas.
  for (const constraint of [
    ...baseline.restricciones.filter((item) => item.tipo !== 'f'),
    ...baseline.restricciones.filter((item) => item.tipo === 'f'),
  ]) {
    await runner.query(
      `ALTER TABLE ${schema}.${quote(constraint.tabla)} ADD CONSTRAINT ${quote(constraint.nombre)} ${constraint.definicion}`,
    );
  }
  const constraints = new Set(
    baseline.restricciones.map((item) => item.nombre),
  );
  for (const index of baseline.indices.filter(
    (item) => !constraints.has(item.nombre),
  )) {
    await runner.query(
      index.definicion.replace(' ON public.', ` ON ${schema}.`),
    );
  }
  for (const table of baseline.seguridad.filter((item) => item.rls)) {
    await runner.query(
      `ALTER TABLE ${schema}.${quote(table.tabla)} ENABLE ROW LEVEL SECURITY`,
    );
  }
}
